  /// 取文案。支持参数占位：t('yesterdayAt', {'time': '14:30'}) → "昨天 14:30"
  String t(String key, [Map<String, String>? params]) {
    final lang = _dict[_langKey] ?? _dict['zh']!;
    var s = lang[key] ?? _dict['zh']![key] ?? key;
    if (params != null) {
      params.forEach((k, v) => s = s.replaceAll('{$k}', v));
    }
    return s;
  }
