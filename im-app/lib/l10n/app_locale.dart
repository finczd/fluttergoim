class _LocaleScope extends InheritedWidget {
  final AppLocalizations localizations;
  const _LocaleScope({required this.localizations, required super.child});
  @override
  bool updateShouldNotify(covariant _LocaleScope old) =>
      old.localizations.locale != localizations.locale;
}

class LocaleProvider extends StatefulWidget {
  final Widget child;
  const LocaleProvider({super.key, required this.child});
  @override
  State<LocaleProvider> createState() => _LocaleProviderState();
  static _LocaleProviderState? of(BuildContext ctx) =>
      ctx.findAncestorStateOfType<_LocaleProviderState>();
}

class _LocaleProviderState extends State<LocaleProvider> {
  /// 初始默认跟随设备语言；initState 异步读出手动选择后覆盖
  Locale _locale = AppLocalizations.matchSystemLocale();
  bool _followingSystem = true;

  Locale get locale => _locale;

  /// 是否正处于"跟随系统"模式（语言弹窗勾选态用）
  bool get isFollowingSystem => _followingSystem;

  @override
  void initState() {
    super.initState();
    _loadSaved();
  }

  /// 读取上次手动选择的语言（'system' = 跟随系统 / localeKey = 具体语言）
  Future<void> _loadSaved() async {
    try {
      final v = await ApiClient.instance.readPref('app_locale');
      if (!mounted || v == null || v.isEmpty || v == 'system') return;
      final saved = AppLocalizations.localeFromKey(v);
      if (saved != null) {
        setState(() {
          _locale = saved;
          _followingSystem = false;
        });
      }
    } catch (_) {}
  }

  /// 四语循环切换：简体中文 → English → 日本語 → 繁體中文（与 AppLocalizations.supportedLangs 一致）
  void toggle() {
    setState(() {
      _locale = AppLocalizations.nextLocale(_locale);
      _followingSystem = false;
    });
    _save(AppLocalizations.localeKey(_locale));
  }

  void setLocale(Locale locale) {
    setState(() {
      _locale = locale;
      _followingSystem = false;
    });
    _save(AppLocalizations.localeKey(locale));
  }

  /// 跟随系统：清除手动选择，立即应用当前设备语言
  void followSystem() {
    setState(() {
      _followingSystem = true;
      _locale = AppLocalizations.matchSystemLocale();
    });
    _save('system');
  }

  void _save(String v) {
    ApiClient.instance.writePref('app_locale', v).catchError((_) {});
  }

  @override
  Widget build(BuildContext context) {
    AppLocalizations._g = AppLocalizations(_locale);
    return _LocaleScope(
      localizations: AppLocalizations(_locale),
      child: widget.child,
    );
  }
}
